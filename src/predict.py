"""
Inference & Prediction Module for SMS Spam Message Detection.
Team 2 - Natural Language Processing

Loads the trained champion pipeline and provides a safe, robust inference API:
- Input validation (empty, whitespace, non-string handling).
- Binary classification: SPAM vs. HAM.
- Probabilistic confidence score.
- Detection of spam keywords, currency, URLs, and numeric codes.
- Human-readable explanation and non-definitive disclaimer.
"""

import os
import sys
from typing import Dict, Any, Optional
import joblib

# Ensure project root is in sys.path
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from src.preprocessing import clean_text, extract_message_features

DEFAULT_MODEL_PATH = os.path.join(PROJECT_ROOT, "models", "best_model_pipeline.joblib")

# Cache the loaded model in memory
_CACHED_MODEL = None
_CACHED_MODEL_PATH = None


def load_inference_pipeline(model_path: Optional[str] = None):
    """
    Loads and caches the trained pipeline from disk.
    """
    global _CACHED_MODEL, _CACHED_MODEL_PATH
    
    if model_path is None:
        model_path = DEFAULT_MODEL_PATH
        
    if _CACHED_MODEL is not None and _CACHED_MODEL_PATH == model_path:
        return _CACHED_MODEL
        
    if not os.path.exists(model_path):
        raise FileNotFoundError(
            f"Model file not found at: {model_path}.\n"
            f"Please run the training pipeline first:\n"
            f"  python src/train_model.py"
        )
        
    model = joblib.load(model_path)
    _CACHED_MODEL = model
    _CACHED_MODEL_PATH = model_path
    return model


def predict_message(raw_text: str, model_path: Optional[str] = None) -> Dict[str, Any]:
    """
    Classifies a raw SMS message into SPAM or HAM with confidence scores and explanation.
    
    Args:
        raw_text: The incoming SMS text string.
        model_path: Optional path to a specific model pipeline.
        
    Returns:
        Dictionary containing prediction results, probabilities, explanation, and metadata.
    """
    # 1. Validation
    if raw_text is None or not isinstance(raw_text, str) or not raw_text.strip():
        return {
            "status": "error",
            "error_message": "Message is empty or contains only whitespace. Please provide valid text.",
            "prediction": "INVALID",
            "is_spam": False,
            "confidence": 0.0,
            "spam_probability": 0.0,
            "ham_probability": 0.0,
            "cleaned_text": "",
            "features": {},
            "explanation": "No text content detected for analysis.",
            "disclaimer": "No prediction generated."
        }

    pipeline = load_inference_pipeline(model_path)
    
    # Extract structural features for explanation
    features = extract_message_features(raw_text)
    cleaned = clean_text(raw_text)
    
    # Perform prediction
    pred_class = int(pipeline.predict([raw_text])[0])
    
    # Calculate probabilities if supported
    spam_prob = 0.5
    ham_prob = 0.5
    if hasattr(pipeline, "predict_proba"):
        probabilities = pipeline.predict_proba([raw_text])[0]
        # Assumes class 0 = HAM, class 1 = SPAM
        ham_prob = float(probabilities[0])
        spam_prob = float(probabilities[1])
        confidence = float(max(ham_prob, spam_prob))
    else:
        confidence = 1.0 if pred_class == 1 else 0.0
        spam_prob = float(pred_class)
        ham_prob = 1.0 - spam_prob

    is_spam = bool(pred_class == 1)
    label = "SPAM" if is_spam else "HAM"

    # Contextual explanation
    reasons = []
    if is_spam:
        if features["has_currency"]:
            reasons.append("contains monetary/currency references or cash promises")
        if features["has_url"]:
            reasons.append("contains external web links / URLs")
        if features["has_numbers"]:
            reasons.append("contains numeric call-back codes or phone numbers")
        if features["exclamation_count"] > 1:
            reasons.append("contains multiple urgent exclamation marks")
        if not reasons:
            reasons.append("vocabulary matches characteristic spam / promotional phrases")
        explanation = f"Classified as SPAM ({confidence*100:.1f}% confidence) because the message " + ", ".join(reasons) + "."
    else:
        explanation = (
            f"Classified as HAM (legitimate, {confidence*100:.1f}% confidence). "
            "The message exhibits natural conversational syntax without aggressive unsolicited promotional markers."
        )

    disclaimer = (
        "Disclaimer: This prediction is an automated statistical estimate generated by an NLP classifier. "
        "A 'SPAM' classification indicates linguistic similarity to unsolicited or suspicious messaging, "
        "not definitive legal proof of fraudulent or criminal intent."
    )

    return {
        "status": "success",
        "raw_text": raw_text,
        "cleaned_text": cleaned,
        "prediction": label,
        "is_spam": is_spam,
        "label_code": pred_class,
        "confidence": round(confidence, 4),
        "spam_probability": round(spam_prob, 4),
        "ham_probability": round(ham_prob, 4),
        "features": features,
        "explanation": explanation,
        "disclaimer": disclaimer
    }


if __name__ == "__main__":
    test_sms = "Congratulations! You have won £1,000 cash prize. Call 08712460324 to claim now!"
    print(f"Testing prediction on: {test_sms}")
    try:
        res = predict_message(test_sms)
        print(f"Result: {res['prediction']} ({res['confidence']*100:.1f}%)")
        print(f"Explanation: {res['explanation']}")
    except Exception as e:
        print(f"Notice: {e}")
